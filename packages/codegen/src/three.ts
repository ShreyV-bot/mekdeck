import { MekdeckError } from '@mekdeck/core';
import type {
  GeometryDesc,
  MaterialDesc,
  PerspectiveCameraObject,
  RGB,
  SceneDescription,
  SceneObject,
  Transform,
} from '@mekdeck/scene';
import { CodeBuilder, IdentAllocator, num, nums, str } from './code-builder.ts';
import type { GeneratedFile, GeneratedProject } from './types.ts';

export interface ThreeOptions {
  /** Used for the page title and package name. */
  readonly projectName?: string;
  /** npm version range for `three` in the generated package.json. */
  readonly threeVersion?: string;
  readonly viteVersion?: string;
}

const DEFAULT_THREE = '^0.180.0';
const DEFAULT_VITE = '^7.0.0';
const BANNER = '// Generated by MekDeck. Do not edit by hand: change the project and regenerate.';

const isDefault = (v: readonly number[], d: number): boolean => v.every((x) => x === d);
const isBlack = (c: RGB): boolean => isDefault(c, 0);

function geometryExpr(g: GeometryDesc): string {
  switch (g.kind) {
    case 'box':
      return `new THREE.BoxGeometry(${nums([g.width, g.height, g.depth])})`;
    case 'sphere':
      return `new THREE.SphereGeometry(${nums([g.radius, g.widthSegments, g.heightSegments])})`;
    case 'plane':
      return `new THREE.PlaneGeometry(${nums([g.width, g.height])})`;
    case 'cylinder':
      return `new THREE.CylinderGeometry(${nums([g.radiusTop, g.radiusBottom, g.height, g.radialSegments])})`;
    case 'torus':
      return `new THREE.TorusGeometry(${nums([g.radius, g.tube, g.radialSegments, g.tubularSegments])})`;
  }
}

const color = (c: RGB): string => `srgb(${nums(c)})`;

function materialLines(m: MaterialDesc): string[] {
  const lines = [`color: ${color(m.color)},`, `roughness: ${num(m.roughness)},`, `metalness: ${num(m.metalness)},`];
  if (!isBlack(m.emissive)) lines.push(`emissive: ${color(m.emissive)},`);
  return lines;
}

function transformLines(id: string, t: Transform, out: CodeBuilder): void {
  if (!isDefault(t.position, 0)) out.line(`${id}.position.set(${nums(t.position)});`);
  if (!isDefault(t.rotation, 0)) out.line(`${id}.rotation.set(${nums(t.rotation)});`);
  if (!isDefault(t.scale, 1)) out.line(`${id}.scale.set(${nums(t.scale)});`);
}

function emitObject(object: SceneObject, parent: string, out: CodeBuilder, idents: IdentAllocator): void {
  const id = idents.claim(object.name);
  out.mark({ origin: object.origin, name: id, kind: object.kind }, () => {
    switch (object.kind) {
      case 'mesh':
        out.line(`const ${id} = new THREE.Mesh(`);
        out.indented(() => {
          out.line(`${geometryExpr(object.geometry)},`);
          out.line('new THREE.MeshStandardMaterial({');
          out.indented(() => materialLines(object.material).forEach((l) => out.line(l)));
          out.line('}),');
        });
        out.line(');');
        out.line(`${id}.name = ${str(object.name)};`);
        transformLines(id, object.transform, out);
        out.line(`${parent}.add(${id});`);
        break;
      case 'group':
        out.line(`const ${id} = new THREE.Group();`);
        out.line(`${id}.name = ${str(object.name)};`);
        transformLines(id, object.transform, out);
        for (const child of object.children) emitObject(child, id, out, idents);
        out.line(`${parent}.add(${id});`);
        break;
      case 'directionalLight':
        out.line(`const ${id} = new THREE.DirectionalLight(${color(object.color)}, ${num(object.intensity)});`);
        out.line(`${id}.name = ${str(object.name)};`);
        out.line(`${id}.position.set(${nums(object.position)});`);
        out.line(`${parent}.add(${id});`);
        break;
      case 'ambientLight':
        out.line(`const ${id} = new THREE.AmbientLight(${color(object.color)}, ${num(object.intensity)});`);
        out.line(`${id}.name = ${str(object.name)};`);
        out.line(`${parent}.add(${id});`);
        break;
      case 'perspectiveCamera':
        throw new MekdeckError('E_CODEGEN_UNSUPPORTED', 'A camera inside the object list cannot be generated; set it as the scene camera instead');
    }
  });
}

function emitCamera(camera: PerspectiveCameraObject | null, out: CodeBuilder): void {
  if (camera === null) {
    out.line('// The graph has no camera, so this is a default one.');
    out.line('const camera = new THREE.PerspectiveCamera(50, window.innerWidth / window.innerHeight, 0.1, 1000);');
    out.line('camera.position.set(0, 2, 6);');
    out.line('camera.lookAt(0, 0, 0);');
    return;
  }
  out.mark({ origin: camera.origin, name: 'camera', kind: camera.kind }, () => {
    out.line(
      `const camera = new THREE.PerspectiveCamera(${num(camera.fov)}, window.innerWidth / window.innerHeight, ${num(camera.near)}, ${num(camera.far)});`,
    );
    out.line(`camera.name = ${str(camera.name)};`);
    out.line(`camera.position.set(${nums(camera.position)});`);
    out.line(`camera.lookAt(${nums(camera.lookAt)});`);
  });
}

function mainJs(scene: SceneDescription): GeneratedFile {
  const out = new CodeBuilder();
  const idents = new IdentAllocator();

  out.line(BANNER);
  out.line("import * as THREE from 'three';");
  out.line();
  out.line('// Colours in MekDeck are sRGB (what you see in a colour picker).');
  out.line('const srgb = (r, g, b) => new THREE.Color().setRGB(r, g, b, THREE.SRGBColorSpace);');
  out.line();
  out.mark({ origin: scene.origin, name: 'scene', kind: 'scene' }, () => {
    out.line('const scene = new THREE.Scene();');
    out.line(`scene.background = ${color(scene.background)};`);
  });
  out.line();
  for (const object of scene.objects) {
    emitObject(object, 'scene', out, idents);
    out.line();
  }
  emitCamera(scene.camera, out);
  out.line();
  out.line('const renderer = new THREE.WebGLRenderer({ antialias: true });');
  out.line('renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));');
  out.line('renderer.setSize(window.innerWidth, window.innerHeight);');
  out.line('document.body.appendChild(renderer.domElement);');
  out.line();
  out.line("window.addEventListener('resize', () => {");
  out.indented(() => {
    out.line('camera.aspect = window.innerWidth / window.innerHeight;');
    out.line('camera.updateProjectionMatrix();');
    out.line('renderer.setSize(window.innerWidth, window.innerHeight);');
  });
  out.line('});');
  out.line();
  out.line('renderer.setAnimationLoop(() => {');
  out.indented(() => out.line('renderer.render(scene, camera);'));
  out.line('});');

  return { path: 'src/main.js', language: 'javascript', content: out.text(), ranges: out.ranges };
}

function slug(name: string): string {
  const s = name
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 100);
  return s === '' ? 'mekdeck-scene' : s;
}

function escapeHtml(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`;

/** A complete Vite + three.js project that renders the scene. */
export function generateThree(scene: SceneDescription, options: ThreeOptions = {}): GeneratedProject {
  const title = options.projectName ?? 'MekDeck scene';
  const files: GeneratedFile[] = [
    {
      path: 'package.json',
      language: 'json',
      content: json({
        name: slug(title),
        private: true,
        version: '0.0.0',
        type: 'module',
        scripts: { dev: 'vite', build: 'vite build', preview: 'vite preview' },
        dependencies: { three: options.threeVersion ?? DEFAULT_THREE },
        devDependencies: { vite: options.viteVersion ?? DEFAULT_VITE },
      }),
    },
    {
      path: 'index.html',
      language: 'html',
      content: [
        '<!doctype html>',
        '<html lang="en">',
        '  <head>',
        '    <meta charset="UTF-8" />',
        '    <meta name="viewport" content="width=device-width, initial-scale=1.0" />',
        `    <title>${escapeHtml(title)}</title>`,
        '    <style>',
        '      html, body { margin: 0; height: 100%; overflow: hidden; background: #000; }',
        '    </style>',
        '  </head>',
        '  <body>',
        '    <script type="module" src="/src/main.js"></script>',
        '  </body>',
        '</html>',
        '',
      ].join('\n'),
    },
    mainJs(scene),
    {
      path: 'README.md',
      language: 'markdown',
      content: [
        `# ${title.replace(/[\r\n]+/g, ' ')}`,
        '',
        'Generated by MekDeck. This code is a snapshot of the scene graph at time 0.',
        'To change the scene, edit the `.mekd` project in MekDeck and export again.',
        '',
        '```sh',
        'npm install',
        'npm run dev',
        '```',
        '',
      ].join('\n'),
    },
    { path: '.gitignore', language: 'text', content: 'node_modules/\ndist/\n' },
  ];
  return { target: 'three', files };
}
